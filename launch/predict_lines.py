# Scores every line in launch/lines.json and writes launch/scores.js, which the video reads.
#
#   python launch/predict_lines.py                       # our model: emotion_model_deberta.pt in the repo root
#   python launch/predict_lines.py --weights path/to.pt  # our model from another path
#   python launch/predict_lines.py --proxy               # placeholder scores from a public GoEmotions model
#
# The video shows a red PLACEHOLDER SCORES tag until this has been run with our own weights.
import argparse
import json
import os
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROXY = "SamLowe/roberta-base-go_emotions"


def our_model(weights):
    # reuse the exact architecture and label order from chat_with_model.py
    sys.path.insert(0, ROOT)
    from chat_with_model import EmotionModel, label_names, DEVICE
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained("microsoft/deberta-v3-base", use_safetensors=True)
    model = EmotionModel().to(DEVICE)
    model.load_state_dict(torch.load(weights, map_location=DEVICE, weights_only=True))
    model.eval()

    def score(text):
        enc = tokenizer(text, max_length=128, padding="max_length", truncation=True, return_tensors="pt")
        with torch.no_grad():
            logits = model(enc["input_ids"].to(DEVICE), enc["attention_mask"].to(DEVICE))
        probs = torch.sigmoid(logits).squeeze().cpu().tolist()
        return {label_names[i]: round(p, 3) for i, p in enumerate(probs)}

    return tokenizer, score


def proxy_model():
    from transformers import AutoTokenizer, pipeline

    tokenizer = AutoTokenizer.from_pretrained("microsoft/deberta-v3-base")
    clf = pipeline("text-classification", model=PROXY, top_k=None)
    return tokenizer, lambda text: {d["label"]: round(d["score"], 3) for d in clf(text)[0]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default=os.path.join(ROOT, "emotion_model_deberta.pt"))
    ap.add_argument("--proxy", action="store_true", help="placeholder scores from a public model, not ours")
    args = ap.parse_args()

    if args.proxy:
        tokenizer, score = proxy_model()
        source, placeholder = f"PLACEHOLDER: {PROXY}, not our model. Re-run without --proxy before posting.", True
    else:
        if not os.path.exists(args.weights):
            sys.exit(f"weights not found: {args.weights}")
        tokenizer, score = our_model(args.weights)
        source, placeholder = f"Our DeBERTa-v3-base model ({os.path.basename(args.weights)})", False

    lines = json.load(open(os.path.join(HERE, "lines.json")))["lines"]
    data = {"source": source, "placeholder": placeholder, "lines": {}}
    for text in lines:
        scores = score(text)
        data["lines"][text] = {"tokens": tokenizer.tokenize(text), "scores": scores}
        top = sorted(scores.items(), key=lambda kv: -kv[1])[:3]
        print(f"{text:<40} " + "  ".join(f"{k} {v:.2f}" for k, v in top))

    with open(os.path.join(HERE, "scores.js"), "w") as f:
        f.write("// Generated by launch/predict_lines.py. Do not edit by hand.\n")
        f.write("window.SCORES = " + json.dumps(data, indent=1) + ";\n")
    print("wrote launch/scores.js" + (" (PLACEHOLDER)" if placeholder else ""))


if __name__ == "__main__":
    main()
